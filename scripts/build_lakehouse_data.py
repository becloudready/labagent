#!/usr/bin/env python3
"""Maintainer tool: package the two source datasets of the dbx-lakehouse pack as pinned table snapshots.

    python scripts/build_lakehouse_data.py --uci online_retail_II.xlsx --synthea synthea_sample_data_csv_latest.zip --out dist-data

Needs openpyxl for the Excel file (maintainers only, learners never run this). Nothing is changed in the source data: rows
are written as they came, split by month so the pack can leave the last months unloaded for an incremental-load exercise.

Sources
- UCI Online Retail II (Chen, D., 2012, https://doi.org/10.24432/C5CG6D), CC BY 4.0. Cite it when you republish.
- Synthea sample data (https://github.com/synthetichealth/synthea-sample-data). The Synthea project states its synthetic open data is
  public domain (https://github.com/synthetichealth/synthea/wiki/DPG). Every person in it is invented.
"""
from __future__ import annotations

import argparse
import csv
import gzip
import io
import json
import sys
import tempfile
import zipfile
from datetime import datetime
from pathlib import Path
from typing import Dict, List

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from labagent import datasets  # noqa: E402

VERSION = "2026.10"
RETAIL_HEADER = ["Invoice", "StockCode", "Description", "Quantity", "InvoiceDate", "Price", "Customer ID", "Country"]
INCOMING_MONTHS = ("2011-10", "2011-11", "2011-12")          # not loaded at launch: learners load them (COPY INTO)
HEALTH_TABLES = ("patients", "encounters", "conditions", "medications", "observations", "procedures", "immunizations",
                 "allergies", "careplans", "organizations", "providers", "payers", "claims")

RETAIL_NOTICE = """Online Retail II
Chen, D. (2012). Online Retail II [Dataset]. UCI Machine Learning Repository. https://doi.org/10.24432/C5CG6D
Licence: Creative Commons Attribution 4.0 International (CC BY 4.0), https://creativecommons.org/licenses/by/4.0/
Changes made: none to the values. The two Excel sheets were written out as CSV files, one per invoice month, gzip compressed.
The two sheets overlap between 2010-12-01 and 2010-12-09, so some invoice lines appear twice. That is in the source.
"""
HEALTH_NOTICE = """Synthea sample data
Generated by Synthea (https://github.com/synthetichealth/synthea), published at https://github.com/synthetichealth/synthea-sample-data.
The Synthea project states that its synthetic open data is public domain: https://github.com/synthetichealth/synthea/wiki/DPG
Every patient, name, address and number in this data is invented. Changes made: a subset of the CSV files, unchanged.
"""


def _gz(path: Path, text: str) -> None:
    with open(path, "wb") as raw, gzip.GzipFile(fileobj=raw, mode="wb", mtime=0, compresslevel=9) as g:
        g.write(text.encode("utf-8"))


def _cell(v) -> str:
    if v is None:
        return ""
    if isinstance(v, datetime):
        return v.strftime("%Y-%m-%d %H:%M:%S")
    return str(v)


def build_retail(xlsx: Path, stage: Path) -> Dict[str, int]:
    try:
        import openpyxl
    except ImportError as e:       # pragma: no cover
        raise SystemExit("openpyxl is needed to read the Excel file: pip install openpyxl") from e
    months: Dict[str, List[List[str]]] = {}
    wb = openpyxl.load_workbook(xlsx, read_only=True, data_only=True)
    total = 0
    for ws in wb.worksheets:
        rows = ws.iter_rows(values_only=True)
        header = [str(h) for h in next(rows)]
        if header != RETAIL_HEADER:
            raise SystemExit(f"unexpected columns in sheet {ws.title!r}: {header}")
        for r in rows:
            if all(v is None for v in r):
                continue
            ts = r[4]
            if not isinstance(ts, datetime):
                raise SystemExit(f"invoice date is not a date: {r!r}")
            months.setdefault(ts.strftime("%Y-%m"), []).append([_cell(v) for v in r])
            total += 1
    counts: Dict[str, int] = {}
    for month, rows in sorted(months.items()):
        buf = io.StringIO()
        w = csv.writer(buf, lineterminator="\n")
        w.writerow(RETAIL_HEADER)
        w.writerows(rows)
        kind = "incoming" if month in INCOMING_MONTHS else "initial"
        name = f"retail_{kind}_{month}.csv.gz"
        _gz(stage / name, buf.getvalue())
        counts[name] = len(rows)
    if sum(counts.values()) != total:
        raise SystemExit("row count mismatch while splitting")
    return counts


def build_healthcare(synthea_zip: Path, stage: Path) -> Dict[str, int]:
    counts: Dict[str, int] = {}
    with zipfile.ZipFile(synthea_zip) as z:
        names = {Path(n).name: n for n in z.namelist() if n.endswith(".csv")}
        for t in HEALTH_TABLES:
            if f"{t}.csv" not in names:
                raise SystemExit(f"{t}.csv is not in the Synthea archive")
            data = z.read(names[f"{t}.csv"])
            (stage / f"healthcare_{t}.csv").write_bytes(data)
            counts[f"healthcare_{t}.csv"] = sum(1 for _ in csv.reader(io.StringIO(data.decode("utf-8")))) - 1
    return counts


def package(domain: str, files: Dict[str, int], stage: Path, source_id: str, notice: str, out: Path) -> Dict:
    (stage / "NOTICE.txt").write_text(notice)
    (stage / "provenance.json").write_text(json.dumps({
        "sources": [{"id": source_id}],
        "info": {"domain": domain, "rows": files, "rows_total": sum(files.values())}}, indent=2, sort_keys=True) + "\n")
    return datasets.build_table_snapshot(stage, f"lakehouse-{domain}", VERSION, out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--uci", type=Path, help="online_retail_II.xlsx from the UCI archive")
    ap.add_argument("--synthea", type=Path, help="synthea_sample_data_csv_latest.zip")
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    if not (a.uci or a.synthea):
        ap.error("give --uci and/or --synthea")
    for flag, builder, domain, source, notice in ((a.uci, build_retail, "retail", "uci-online-retail-ii", RETAIL_NOTICE),
                                                  (a.synthea, build_healthcare, "healthcare", "synthea-sample", HEALTH_NOTICE)):
        if not flag:
            continue
        with tempfile.TemporaryDirectory() as tmp:
            stage = Path(tmp)
            counts = builder(flag, stage)
            m = package(domain, counts, stage, source, notice, a.out)
            print(f"{domain}: {m['file']}  {m['bytes']:,} bytes  sha256 {m['sha256']}  rows {sum(counts.values()):,}")


if __name__ == "__main__":
    main()
