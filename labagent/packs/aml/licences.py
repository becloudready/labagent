"""Where every AML input comes from, under what licence, and whether it may be written into a published snapshot.

Rule: a snapshot only ever contains sources whose `mode` is "bundled". Everything else is fetched on the user's machine at
launch, or imported only when the user asks and has accepted the licence. `assert_redistributable` is the gate that
`build_table_snapshot` calls, so a fetch-only source cannot reach a release by accident.
"""
from __future__ import annotations

from typing import Dict, Iterable


class LicenceError(Exception):
    pass


SOURCES: Dict[str, Dict[str, str]] = {
    "synthetic": {"licence": "CC-BY-4.0", "mode": "bundled", "note": "Generated by labagent. Names, numbers and documents are invented."},
    "ofac-sdn": {"licence": "US government work (public domain)", "mode": "bundled",
                 "note": "A fixed set of 12 entity names with their SDN uid. Seeds screening practice. Not a current list."},
    "ecfr-31-cfr-x": {"licence": "US government work (public domain)", "mode": "bundled",
                      "note": "31 CFR Chapter X from govinfo bulk XML. The eCFR is an unofficial compilation."},
    "justice-laws-ca": {"licence": "Open Government Licence - Canada", "mode": "bundled",
                        "note": "PCMLTFA and regulations from Justice Laws XML. Needs attribution and a notice that this is not the official version."},
    "ffiec-bsa-aml": {"licence": "not verified", "mode": "fetched", "note": "Fetched on the user's machine at launch."},
    "fintrac": {"licence": "Government of Canada terms (not reviewed)", "mode": "fetched", "note": "Indicators and STR guidance. Fetched at launch."},
    "opensanctions": {"licence": "CC-BY-NC-4.0", "mode": "fetched", "note": "Non-commercial only. Opt-in fetch with an explicit acknowledgement."},
    "ibm-aml-kaggle": {"licence": "CDLA-Sharing-1.0 (per search result, not verified against the Kaggle page)", "mode": "import",
                       "note": "User supplies Kaggle credentials. Never bundled."},
    "saml-d": {"licence": "not verified", "mode": "import", "note": "User downloads it. Never bundled."},
}


def assert_redistributable(source_ids: Iterable[str]) -> None:
    bad = []
    for s in source_ids:
        info = SOURCES.get(s)
        if info is None:
            bad.append(f"{s} (unknown source)")
        elif info["mode"] != "bundled":
            bad.append(f"{s} ({info['mode']} only, {info['licence']})")
    if bad:
        raise LicenceError("these sources may not be written into a snapshot: " + "; ".join(bad))
